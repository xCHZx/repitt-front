// Generates src/api/v1.d.ts from the frozen v1 contract (src/api/openapi.json).
// Drops the operations the front must never call (guide §7): /v1/admin/*, /health*, Stripe webhook.
import { readFile, writeFile } from 'node:fs/promises'
import openapiTS, { astToString } from 'openapi-typescript'

const SPEC = new URL('../src/api/openapi.json', import.meta.url)
const OUT = new URL('../src/api/v1.d.ts', import.meta.url)

const isExcluded = path =>
  path.startsWith('/v1/admin') || path.startsWith('/health') || path === '/v1/billing/webhooks/stripe'

const spec = JSON.parse(await readFile(SPEC, 'utf8'))
spec.paths = Object.fromEntries(Object.entries(spec.paths).filter(([path]) => !isExcluded(path)))

const ast = await openapiTS(spec, { alphabetize: true, exportType: true })
const header = '/* eslint-disable */\n// Generated by scripts/gen-api-types.mjs from src/api/openapi.json — do not edit by hand.\n\n'

await writeFile(OUT, header + astToString(ast))
console.log(`api types: ${Object.keys(spec.paths).length} paths → src/api/v1.d.ts`)
